<!DOCTYPE html>
{{--
    lang="es" y translate="no": la interfaz está en español y el traductor
    integrado del navegador (Edge/Chrome) reescribe los nodos de texto que React
    controla. Al re-renderizar, React intenta quitar un nodo que el traductor ya
    reemplazó y revienta con "Failed to execute 'removeChild' on 'Node'".
--}}
<html lang="es" translate="no" @class(['dark' => ($appearance ?? 'system') == 'dark'])>
    <head>
        <meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <meta name="google" content="notranslate">

        {{-- Inline script to detect system dark mode preference and apply it immediately --}}
        <script>
            (function() {
                const appearance = '{{ $appearance ?? "system" }}';

                if (appearance === 'system') {
                    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;

                    if (prefersDark) {
                        document.documentElement.classList.add('dark');
                    }
                }
            })();
        </script>

        {{-- Inline style to set the HTML background color based on our theme in app.css --}}
        <style>
            html {
                background-color: oklch(1 0 0);
            }

            html.dark {
                background-color: oklch(0.145 0 0);
            }
        </style>

        <title inertia>{{ config('app.name', 'Steelex') }}</title>

        @viteReactRefresh
        @vite(['resources/js/app.tsx', "resources/js/pages/{$page['component']}.tsx"])
        @inertiaHead
    </head>
    <body class="notranslate font-sans antialiased">
        @inertia
    </body>
</html>
